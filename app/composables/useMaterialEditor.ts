import type { Document, Note } from '~/types'

/** Bounds of "Gerar 3 cards com IA" on a selection (RF-B5: 40–4.000 characters, contained in the note). */
export const SELECTION_MIN = 40
export const SELECTION_MAX = 4000

/**
 * The text of the open material (prd-4c-material-v3 §3.2): opens the note (GET /notes/{id}, POST
 * /notes/{id}/opened) and its PDF (GET /documents/{id}: the notices of the PDF and the "escrevendo"
 * state), and wires the autosave with the local draft, the note still being generated (only the note and
 * its PDF every 4 s, G4), "Melhorar com IA", the card workshop (the whole note or a selection) and
 * "Perguntar ao tira-dúvidas". The numbers around the text are `useMaterial`; `onCardsChanged` refreshes them.
 */
export function useMaterialEditor(topicId: Ref<string>, noteId: Ref<string>, onCardsChanged: () => Promise<void> | void = () => {}) {
  const { $api } = useNuxtApp()
  const noteStore = useNoteStore()
  const scopeTopic = computed<string | null>(() => topicId.value)

  const editor = useNoteEditor(scopeTopic)
  const improve = useNoteImprove(scopeTopic)
  const workshop = useCardWorkshop({
    topicId: scopeTopic,
    onReload: async () => { await onCardsChanged() },
  })

  /** The open note could not be found (deleted, or someone else's) */
  const missing = ref(false)
  const document = shallowRef<Document | null>(null)

  const generating = computed(() => document.value?.note_generation_status === 'generating')

  async function loadDocument(id: string | null | undefined) {
    if (!id) {
      document.value = null
      return
    }
    try {
      const res = await $api<{ data: Document }>(`/documents/${id}`)
      document.value = res.data
    } catch (e) {
      reportApiError(e, { silent: true })
    }
  }

  /** Opens the note of the route: the editor first, then its PDF. */
  async function open() {
    missing.value = false
    document.value = null
    const id = noteId.value
    const stub = { id, title: '', topic_id: topicId.value, word_count: 0, plain_preview: null, flashcards_count: 0, source_document_id: null, last_ai_transform_at: null, cards_generated_at: null, created_at: '', updated_at: '' }
    await editor.openNoteEditor(stub)
    const full = editor.editingNote.value as Note | null
    if (!full || full.id !== id || !('content' in full)) {
      if (id === noteId.value) missing.value = true
      return
    }
    void loadDocument(full.source_document_id)
  }

  // A note still being generated by the PDF job: read-only, its content refreshed every 4 s
  const refresh = usePoll(async (signal) => {
    const id = noteId.value
    const [note, doc] = await Promise.all([
      $api<{ data: Note }>(`/notes/${id}`, { signal }),
      document.value ? $api<{ data: Document }>(`/documents/${document.value.id}`, { signal }) : Promise.resolve(null),
    ])
    if (id !== noteId.value) return
    if (note.data?.content) editor.noteContent.value = note.data.content
    if (doc) document.value = doc.data
  }, { interval: 4000, immediate: false, until: () => !generating.value })
  watch(generating, (on) => { if (on) refresh.start(); else refresh.stop() })

  // "Melhorar com IA": the preview replaces the editor content until applied or discarded
  watch(() => improve.state.value, (state) => {
    if (state === 'preview' && improve.improvedContent.value) editor.noteContent.value = improve.improvedContent.value
  })

  function improveNote() {
    if (editor.editingNote.value) improve.improve(editor.editingNote.value)
  }

  function applyImprove() {
    const content = improve.apply()
    if (content && noteStore.current) {
      editor.noteContent.value = content
      // `improved` marks last_ai_transform_at
      void noteStore.update(noteStore.current.id, { content, improved: true })
    }
  }

  function discardImprove() {
    const content = improve.discard()
    if (content) editor.noteContent.value = content
  }

  function generateCards() {
    if (editor.editingNote.value) workshop.generate('notes', editor.editingNote.value.id)
  }

  /** "Gerar 3 cards com IA" (RF-B5): the API checks the excerpt is in the note and asks 3 cards. */
  function generateFromSelection(text: string) {
    const note = editor.editingNote.value
    const excerpt = text.trim()
    if (!note || excerpt.length < SELECTION_MIN || excerpt.length > SELECTION_MAX) return
    workshop.generate('selection', note.id, undefined, excerpt)
  }

  /** "Perguntar ao tira-dúvidas": the tira-dúvidas with the scope, the note's PDF and the excerpt. */
  function askAboutSelection(text?: string) {
    const sel = (text ?? window.getSelection()?.toString() ?? '').trim()
    if (!sel) return
    const excerpt = sel.slice(0, 600)
    useChatStore().ask({
      topicId: topicId.value,
      documentId: editor.editingNote.value?.source_document_id ?? undefined,
      excerpt,
      source: 'note_help',
    }, `Me explica este trecho da minha nota: "${excerpt}"`)
  }

  onScopeDispose(() => {
    editor.flushPendingSave()
    refresh.stop()
  })

  return {
    ...editor,
    improve,
    workshop,
    missing,
    document,
    generating,
    open,
    loadDocument,
    improveNote,
    applyImprove,
    discardImprove,
    generateCards,
    generateFromSelection,
    askAboutSelection,
  }
}
