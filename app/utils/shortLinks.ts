/**
 * Short addresses written on social posts (social-baigi skill): TikTok without a link in the bio, Shorts whose
 * description does not click and the Instagram bio (prd-entrada-comecar RF-F4). The address typed by hand arrives without UTM, so these redirect on the edge to the
 * entry of /comecar with the campaign of the channel, and the first touch (utils/firstTouch) records it on /comecar.
 * /edital is written in the YouTube Shorts that end on the free edital tool (relatorio-redes-2026-11-20): it goes to the
 * tool, not to /comecar, with utm_campaign=video so the visit and the signup are told apart from the profile link.
 * /yt<N> and /tk<N> (N from 27 to 199) exist to measure signups per video: each video shows its own address on screen
 * (e.g. baigi.com.br/yt27 on YouTube Shorts, baigi.com.br/tk27 on TikTok) and redirects to /comecar with
 * utm_content=v<NNN> (3 digits), which the first touch records. They are generated by code, not written by hand.
 * 302 on purpose: the target can change later without browsers caching it.
 */
export const VIDEO_FIRST = 27
export const VIDEO_LAST = 199

const VIDEO_CHANNELS = { yt: 'youtube', tk: 'tiktok' } as const

/** Per-video short links: /yt27 ... /yt199 and /tk27 ... /tk199. */
export function videoShortLinks(): Record<string, string> {
  const links: Record<string, string> = {}
  for (const [prefix, source] of Object.entries(VIDEO_CHANNELS)) {
    for (let n = VIDEO_FIRST; n <= VIDEO_LAST; n++) {
      links[`/${prefix}${n}`] = `/comecar?utm_source=${source}&utm_medium=social&utm_campaign=video&utm_content=v${String(n).padStart(3, '0')}`
    }
  }
  return links
}

/** The fixed links: they become routeRules (edge redirects). */
export const PROFILE_SHORT_LINKS: Record<string, string> = {
  '/tiktok': '/comecar?utm_source=tiktok&utm_medium=social&utm_campaign=perfil',
  '/yt': '/comecar?utm_source=youtube&utm_medium=social&utm_campaign=perfil',
  '/ig': '/comecar?utm_source=instagram&utm_medium=bio',
  '/edital': '/ferramentas/edital-verticalizado?utm_source=youtube&utm_campaign=video',
}

/** All the short links (fixed + per video). */
export const SHORT_LINKS: Record<string, string> = { ...PROFILE_SHORT_LINKS, ...videoShortLinks() }

/**
 * The routeRules of the fixed short links (temporary redirects). The ~350 per-video links stay out of the routeRules on
 * purpose: Nuxt compiles every redirect rule into the client router, and they would add ~6 KB gzip to entrada+layout
 * (over the budget). They are served by server/middleware/videoShortLinks.ts instead.
 */
export function shortLinkRules(): Record<string, { redirect: { to: string, statusCode: 302 } }> {
  return Object.fromEntries(Object.entries(PROFILE_SHORT_LINKS).map(([from, to]) => [from, { redirect: { to, statusCode: 302 as const } }]))
}
