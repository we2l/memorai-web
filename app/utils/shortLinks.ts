/**
 * Short addresses written on social posts (social-baigi skill): TikTok without a link in the bio, Shorts whose
 * description does not click and the Instagram bio (prd-entrada-comecar RF-F4). The address typed by hand arrives without UTM, so these redirect on the edge to the
 * entry of /comecar with the campaign of the channel, and the first touch (utils/firstTouch) records it on /comecar.
 * /edital is written in the YouTube Shorts that end on the free edital tool (relatorio-redes-2026-11-20): it goes to the
 * tool, not to /comecar, with utm_campaign=video so the visit and the signup are told apart from the profile link. The
 * same video is posted on TikTok and Facebook too, so the network comes from the in-app browser that opened the link
 * (editalShortLink); a typed address in a plain browser has no trace of the network and stays youtube.
 * /yt<N> and /tk<N> (N from 27 to 199) exist to measure signups per video: each video shows its own address on screen
 * (e.g. baigi.com.br/yt27 on YouTube Shorts, baigi.com.br/tk27 on TikTok) and redirects with utm_content=v<NNN>
 * (3 digits), which the first touch records. They go to /comecar, or to the tool of the video (VIDEO_TARGETS). They are
 * generated by code, not written by hand.
 * 302 on purpose: the target can change later without browsers caching it.
 */
export const VIDEO_FIRST = 27
export const VIDEO_LAST = 199

export const EDITAL_TOOL_PATH = '/ferramentas/edital-verticalizado'

/** Videos that end on a free tool instead of /comecar: V031 ("Saiu o edital"), whose address is /yt31 and /tk31. */
export const VIDEO_TARGETS: Readonly<Record<number, string>> = { 31: EDITAL_TOOL_PATH }

const VIDEO_CHANNELS = { yt: 'youtube', tk: 'tiktok' } as const

/** Per-video short links: /yt27 ... /yt199 and /tk27 ... /tk199. */
export function videoShortLinks(): Record<string, string> {
  const links: Record<string, string> = {}
  for (const [prefix, source] of Object.entries(VIDEO_CHANNELS)) {
    for (let n = VIDEO_FIRST; n <= VIDEO_LAST; n++) {
      const target = VIDEO_TARGETS[n] ?? '/comecar'
      links[`/${prefix}${n}`] = `${target}?utm_source=${source}&utm_medium=social&utm_campaign=video&utm_content=v${String(n).padStart(3, '0')}`
    }
  }
  return links
}

/**
 * The network of an in-app browser (TikTok, Instagram, Facebook), from its user agent; null for any other browser
 * (YouTube opens links in the phone's own browser, with no mark of its own).
 */
export function inAppNetwork(userAgent: string | null | undefined): 'tiktok' | 'instagram' | 'facebook' | null {
  const ua = userAgent ?? ''
  if (/musical_ly|BytedanceWebview|ByteLocale|TikTok/i.test(ua)) return 'tiktok'
  // Before Facebook: the Instagram app also carries FBAN/FBAV marks on some versions
  if (/Instagram/i.test(ua)) return 'instagram'
  if (/FBAN|FBAV|FB_IAB|FBIOS|FB4A/.test(ua)) return 'facebook'
  return null
}

/** /edital: the edital tool, tagged with the network of the in-app browser, else youtube (where it started). */
export function editalShortLink(userAgent: string | null | undefined): string {
  const source = inAppNetwork(userAgent) ?? 'youtube'
  return `${EDITAL_TOOL_PATH}?utm_source=${source}&utm_medium=social&utm_campaign=video`
}

/** The fixed profile links: they become routeRules (edge redirects). */
export const PROFILE_SHORT_LINKS: Record<string, string> = {
  '/tiktok': '/comecar?utm_source=tiktok&utm_medium=social&utm_campaign=perfil',
  '/yt': '/comecar?utm_source=youtube&utm_medium=social&utm_campaign=perfil',
  '/ig': '/comecar?utm_source=instagram&utm_medium=bio',
}

/** All the short links (fixed + /edital with no in-app browser + per video). */
export const SHORT_LINKS: Record<string, string> = { ...PROFILE_SHORT_LINKS, '/edital': editalShortLink(null), ...videoShortLinks() }

/**
 * The routeRules of the fixed short links (temporary redirects). /edital (it reads the user agent) and the ~350
 * per-video links stay out of the routeRules on purpose: Nuxt compiles every redirect rule into the client router, and
 * they would add ~6 KB gzip to entrada+layout (over the budget). They are served by server/middleware/videoShortLinks.ts.
 */
export function shortLinkRules(): Record<string, { redirect: { to: string, statusCode: 302 } }> {
  return Object.fromEntries(Object.entries(PROFILE_SHORT_LINKS).map(([from, to]) => [from, { redirect: { to, statusCode: 302 as const } }]))
}

/** The target of a short link served by the server middleware (/edital, /ytN, /tkN), or null. */
export function serverShortLink(path: string, userAgent: string | null | undefined, links: Record<string, string>): string | null {
  if (path === '/edital') return editalShortLink(userAgent)
  return links[path] ?? null
}
